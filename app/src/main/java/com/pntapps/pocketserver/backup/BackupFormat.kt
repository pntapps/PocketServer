package com.pntapps.pocketserver.backup

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.apache.commons.compress.archivers.tar.TarArchiveInputStream
import java.io.IOException
import java.io.InputStream
import java.time.LocalDate
import java.util.Locale
import java.util.zip.GZIPInputStream
import java.util.zip.ZipException

/**
 * Describes a backup. Always the first entry of the archive so a restore can check what it is
 * looking at (and refuse anything else) before touching any data.
 */
@Serializable
data class BackupManifest(
    val format: String = BackupFormat.MAGIC,
    val version: Int = BackupFormat.VERSION,
    /** Epoch millis. */
    @SerialName("created") val createdAt: Long,
    /** PocketServer versionName that made the backup. */
    @SerialName("appVersion") val appVersion: String,
    /** Catalog ids stored under apps/<id>/ in the archive. */
    val apps: List<String>,
    /** The archive holds shared/ (the /shared folder). */
    val shared: Boolean,
    /**
     * The archive holds ca/ (PocketServer's local certificate authority, private key included), so
     * devices that trust it keep working after a restore. Absent in older backups.
     */
    val ca: Boolean = false,
)

class InvalidBackupException(message: String) : IOException(message)

/**
 * Archive layout (paths inside the .tar.gz):
 *   pocketserver-backup.json   manifest, first entry
 *   apps/<id>/...              /opt/pocketserver/apps/<id> minus cache and logs
 *   shared/...                 /shared, optional
 * Pure JVM code so it can be unit tested.
 */
object BackupFormat {
    const val MAGIC = "pocketserver-backup"
    const val VERSION = 1
    const val MANIFEST_NAME = "pocketserver-backup.json"
    private const val MAX_MANIFEST_BYTES = 64 * 1024

    /** Directories inside apps/<id>/ that are regenerated by the app and never backed up. */
    val EXCLUDED_DIRS = listOf("cache", "log", "logs")

    private val idPattern = Regex("[a-z0-9][a-z0-9_-]{0,63}")

    private val json = Json { ignoreUnknownKeys = true; prettyPrint = true; encodeDefaults = true }

    fun encode(manifest: BackupManifest): String = json.encodeToString(BackupManifest.serializer(), manifest)

    /** Parses and validates a manifest; throws [InvalidBackupException] with a user-facing message. */
    fun decode(text: String): BackupManifest {
        val m = try {
            json.decodeFromString(BackupManifest.serializer(), text)
        } catch (e: Exception) {
            throw InvalidBackupException("Not a PocketServer backup (unreadable manifest).")
        }
        validate(m)
        return m
    }

    fun validate(m: BackupManifest) {
        if (m.format != MAGIC) throw InvalidBackupException("Not a PocketServer backup.")
        if (m.version < 1) throw InvalidBackupException("Not a PocketServer backup (bad version).")
        if (m.version > VERSION) {
            throw InvalidBackupException("This backup was made by a newer PocketServer (${m.appVersion}). Update the app to restore it.")
        }
        m.apps.forEach { if (!idPattern.matches(it)) throw InvalidBackupException("Backup is damaged (bad app id).") }
        if (m.apps.toSet().size != m.apps.size) throw InvalidBackupException("Backup is damaged (duplicate app).")
        if (m.apps.isEmpty() && !m.shared) throw InvalidBackupException("Backup is empty.")
    }

    /**
     * Reads the manifest from the start of a .tar.gz stream. Only the first entry is read, so this is
     * cheap even for huge archives. Does not close [input].
     */
    fun readManifest(input: InputStream): BackupManifest {
        val tar = try {
            TarArchiveInputStream(GZIPInputStream(input))
        } catch (e: ZipException) {
            throw InvalidBackupException("Not a PocketServer backup (not a .tar.gz file).")
        } catch (e: java.io.EOFException) {
            throw InvalidBackupException("Not a PocketServer backup (file is empty or truncated).")
        }
        val entry = try {
            tar.nextEntry
        } catch (e: BackupCryptoException) {
            throw e // Wrong passphrase or tampering says more than "not a tar archive".
        } catch (e: IOException) {
            throw InvalidBackupException("Not a PocketServer backup (not a tar archive).")
        } ?: throw InvalidBackupException("Not a PocketServer backup (archive is empty).")
        if (entry.name.removePrefix("./") != MANIFEST_NAME || !entry.isFile) {
            throw InvalidBackupException("Not a PocketServer backup (manifest missing).")
        }
        if (entry.size > MAX_MANIFEST_BYTES) throw InvalidBackupException("Not a PocketServer backup (manifest too large).")
        // InputStream.readNBytes needs API 33; minSdk is 29.
        val bytes = ByteArray(entry.size.toInt())
        var off = 0
        while (off < bytes.size) {
            val n = tar.read(bytes, off, bytes.size - off)
            if (n < 0) throw InvalidBackupException("Not a PocketServer backup (file is truncated).")
            off += n
        }
        return decode(bytes.decodeToString())
    }

    /** MIME type for the file picker; encrypted backups are opaque bytes. */
    fun mimeType(encrypted: Boolean) = if (encrypted) "application/octet-stream" else "application/gzip"

    fun defaultFileName(date: LocalDate = LocalDate.now(), encrypted: Boolean = false) =
        "pocketserver-%04d%02d%02d.tar.gz".format(Locale.US, date.year, date.monthValue, date.dayOfMonth) +
            (if (encrypted) ".enc" else "")

    /**
     * argv for creating the archive on stdout, run inside Ubuntu. [manifestDir] holds the manifest
     * file (guest path). Excludes are anchored and `*` does not cross `/`, so only apps/<id>/cache
     * (log, logs) are skipped, never a nested folder that happens to share the name.
     */
    fun createArgs(manifestDir: String, appIds: List<String>, includeShared: Boolean, includeCa: Boolean = false): List<String> = buildList {
        add("tar"); add("-czf"); add("-")
        add("--anchored"); add("--no-wildcards-match-slash")
        EXCLUDED_DIRS.forEach { add("--exclude=apps/*/$it") }
        add("-C"); add(manifestDir); add(MANIFEST_NAME)
        if (appIds.isNotEmpty()) {
            add("-C"); add("/opt/pocketserver")
            appIds.forEach { add("apps/$it") }
            if (includeCa) add("ca")
        }
        if (includeShared) { add("-C"); add("/"); add("shared") }
    }

    /** argv for extracting the members a manifest promises into [stageDir] (guest path) from stdin. */
    fun extractArgs(stageDir: String, appIds: List<String>, includeShared: Boolean, includeCa: Boolean = false): List<String> = buildList {
        add("tar"); add("-xzf"); add("-"); add("-C"); add(stageDir); add("--no-same-owner")
        add(MANIFEST_NAME)
        appIds.forEach { add("apps/$it") }
        if (includeCa) add("ca")
        if (includeShared) add("shared")
    }

    fun formatBytes(bytes: Long): String = when {
        bytes < 1024 -> "$bytes B"
        bytes < 1024L * 1024 -> "%.0f KB".format(Locale.US, bytes / 1024.0)
        bytes < 1024L * 1024 * 1024 -> "%.1f MB".format(Locale.US, bytes / 1048576.0)
        else -> "%.2f GB".format(Locale.US, bytes / 1073741824.0)
    }
}
